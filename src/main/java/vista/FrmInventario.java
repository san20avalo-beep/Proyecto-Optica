    private void aplicarColoresFilas() {

    TblMediciones.setDefaultRenderer(Object.class,
        new DefaultTableCellRenderer() {

            @Override
            public Component getTableCellRendererComponent(
                    JTable table,
                    Object value,
                    boolean isSelected,
                    boolean hasFocus,
                    int row,
                    int column) {

                Component c = super.getTableCellRendererComponent(
                        table,
                        value,
                        isSelected,
                        hasFocus,
                        row,
                        column);

                if (!isSelected) {

                    if (row % 2 == 0) {
                        c.setBackground(Color.WHITE);
                    } else {
                        c.setBackground(new Color(240, 245, 250));
                    }

                    c.setForeground(Color.BLACK);
                }

                return c;
            }
        });
}
    


